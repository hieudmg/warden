// The complete captured English warning, not a substring/fingerprint regex.
// Only CRLF is normalized by the consumer; no other locale or layout is known.
func certutilFixtureWarningBody(ca certutilFixtureCAIdentity) string {
	thumb := ca.Thumbprint[:8] + " " + ca.Thumbprint[8:16] + " " + ca.Thumbprint[16:24] + " " + ca.Thumbprint[24:32] + " " + ca.Thumbprint[32:]
	return fmt.Sprintf(`You are about to install a certificate from a certification authority (CA) claiming to represent:

%s

Windows cannot validate that the certificate is actually from "%s". You should confirm its origin by contacting "%s". The following number will assist you in this process:

Thumbprint (sha1): %s

Warning:
If you install this root certificate, Windows will automatically trust any certificate issued by this CA. Installing a certificate with an unconfirmed thumbprint is a security risk. If you click "Yes" you acknowledge this risk.

Do you want to install this certificate?
`, ca.CN, ca.CN, ca.CN, thumb)
}

// An attempt is consumed before calling the native dispatcher, including on
// timeout or ambiguous failure. This state belongs to one bounded helper only.
type certutilFixtureConsentState struct{ attempted bool }

func (s *certutilFixtureConsentState) dispatch(ctx context.Context, target certutilFixtureControlTarget, observed []certutilFixtureDialog, fresh func() ([]certutilFixtureDialog, error), click func(certutilFixtureDialog) error) error {
	if s.attempted || fresh == nil || click == nil {
		return errors.New("consent attempt consumed or dispatcher unavailable")
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	if err := certutilFixtureControlIdentityEvidence(target, observed); err != nil {
		return err
	}
	verified, err := fresh()
	if err != nil {
		return err
	}
	// Re-read the immutable public DER after the fresh complete native snapshot.
	if err := certutilFixtureControlIdentityEvidence(target, verified); err != nil {
		return err
	}
	if !reflect.DeepEqual(observed, verified) {
		return errors.New("owned dialog/control handles or evidence changed before consent")
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	s.attempted = true
	return click(verified[0])
}

func certutilFixtureCapturedDialog(t *testing.T, target certutilFixtureControlTarget) certutilFixtureDialog {
	t.Helper()
	b, err := os.ReadFile("testdata/certutil-security-warning.txt")
	if err != nil {
		t.Fatal(err)
	}
	// Actual complete R6 WM_GETTEXT capture, not text generated by the matcher.
	// Historical expected DER was not printed; substitute this test's identity.
	body := strings.ReplaceAll(string(b), "Warden T16 isolated fixture 76e72f39bac686f832194ed75b840093", target.CA.CN)
	body = strings.ReplaceAll(body, "D0BB49C3 88ACCE50 F9C5FA06 2BCA2116 4866AFDB", certutilFixtureTestThumb(target.CA.Thumbprint))
	return certutilFixtureDialog{HWND: 10, PID: uint32(target.PID), TID: 42, Creation: target.Creation, Class: "#32770", Caption: "Security Warning", Complete: true,
		Controls: []certutilFixtureControl{
			{HWND: 11, Parent: 10, PID: uint32(target.PID), TID: 42, ID: 6, Class: "Button", Text: "&Yes", Complete: true},
			{HWND: 12, Parent: 10, PID: uint32(target.PID), TID: 42, ID: 7, Class: "Button", Text: "&No", Complete: true},
			{HWND: 13, Parent: 10, PID: uint32(target.PID), TID: 42, ID: 20, Class: "Static", Complete: true},
			{HWND: 14, Parent: 10, PID: uint32(target.PID), TID: 42, ID: 65535, Class: "Static", Text: body, Complete: true},
		}}
}

func certutilFixtureTestThumb(thumb string) string {
	return thumb[:8] + " " + thumb[8:16] + " " + thumb[16:24] + " " + thumb[24:32] + " " + thumb[32:]
}

func TestCertutilFixtureConsentCapturedWarning(t *testing.T) {
	ca := certutilFixtureControlTestCA(t)
	target := certutilFixtureControlTarget{PID: 1234, Creation: 5678, CA: ca}
	for _, lineEndings := range []string{"CRLF", "LF"} {
		t.Run(lineEndings, func(t *testing.T) {
			d := certutilFixtureCapturedDialog(t, target)
			d.Controls[3].Text = strings.ReplaceAll(d.Controls[3].Text, "\r\n", "\n")
			if lineEndings == "CRLF" {
				d.Controls[3].Text = strings.ReplaceAll(d.Controls[3].Text, "\n", "\r\n")
			}
			if err := certutilFixtureControlIdentityEvidence(target, []certutilFixtureDialog{d}); err != nil {
				t.Fatalf("actual compound warning rejected: %v", err)
			}
		})
	}
}

func TestCertutilFixtureConsentInvalidTargetNeverActs(t *testing.T) {
	for _, name := range []string{"PID", "creation", "CN", "thumbprint", "DER", "missing file", "partial CN", "partial thumbprint"} {
		t.Run(name, func(t *testing.T) {
			ca := certutilFixtureControlTestCA(t)
			target := certutilFixtureControlTarget{PID: 1234, Creation: 5678, CA: ca}
			d := certutilFixtureCapturedDialog(t, target)
			switch name {
			case "PID":
				target.PID = os.Getpid()
			case "creation":
				target.Creation = 0
			case "CN":
				target.CA.CN += "wrong"
			case "thumbprint":
				target.CA.Thumbprint = strings.Repeat("0", 40)
			case "DER":
				target.CA.DERSHA256[0] ^= 1
			case "missing file":
				target.CA.File += ".missing"
			case "partial CN":
				target.CA.CN = "Warden T16 isolated fixture"
			case "partial thumbprint":
				target.CA.Thumbprint = ca.Thumbprint[:38]
			}
			var state certutilFixtureConsentState
			reads, actions := 0, 0
			err := state.dispatch(context.Background(), target, []certutilFixtureDialog{d}, func() ([]certutilFixtureDialog, error) { reads++; return []certutilFixtureDialog{d}, nil }, func(certutilFixtureDialog) error { actions++; return nil })
			if err == nil || reads != 0 || actions != 0 || state.attempted {
				t.Fatalf("unsafe target: err=%v reads=%d actions=%d attempted=%v", err, reads, actions, state.attempted)
			}
		})
	}
}

func TestCertutilFixtureConsentOneActionAndFreshGuards(t *testing.T) {
	for _, name := range []string{"one action", "API failure", "ambiguous timeout", "reread failure", "CA changed", "CA removed", "cancelled", "cancel during reread", "root reused", "Yes reused", "fresh ownership", "fresh layout", "fresh body", "fresh creation", "fresh incomplete", "fresh extra dialog"} {
		t.Run(name, func(t *testing.T) {
			ca := certutilFixtureControlTestCA(t)
			target := certutilFixtureControlTarget{PID: 1234, Creation: 5678, CA: ca}
			d := certutilFixtureCapturedDialog(t, target)
			state := certutilFixtureConsentState{}
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			if name == "cancelled" {
				cancel()
			}
			reads, actions := 0, 0
			read := func() ([]certutilFixtureDialog, error) {
				reads++
				f := d
				f.Controls = slices.Clone(d.Controls)
				switch name {
				case "reread failure":
					return nil, errors.New("bounded native read failed")
				case "CA changed":
					if err := os.WriteFile(ca.File, []byte("changed public DER"), 0600); err != nil {
						t.Fatal(err)
					}
				case "CA removed":
					if err := os.Remove(ca.File); err != nil {
						t.Fatal(err)
					}
				case "cancel during reread":
					cancel()
				case "root reused":
					f.HWND++
					for i := range f.Controls {
						f.Controls[i].Parent = f.HWND
					}
				case "Yes reused":
					f.Controls[0].HWND = 99
				case "fresh ownership":
					f.Controls[0].TID++
				case "fresh layout":
					f.Controls[0].Text = "Yes"
				case "fresh body":
					f.Controls[3].Text += "another certificate"
				case "fresh creation":
					f.Creation++
				case "fresh incomplete":
					f.Complete = false
				case "fresh extra dialog":
					return []certutilFixtureDialog{f, f}, nil
				}
				return []certutilFixtureDialog{f}, nil
			}
			click := func(f certutilFixtureDialog) error {
				actions++
				if f.HWND != d.HWND || !slices.Equal(f.Controls, d.Controls) {
					t.Error("dispatcher did not receive the fresh exact target")
				}
				if name == "API failure" || name == "ambiguous timeout" {
					return fmt.Errorf("%s; attempt consumed", name)
				}
				return nil
			}
			err := state.dispatch(ctx, target, []certutilFixtureDialog{d}, read, click)
			attempted := name == "one action" || name == "API failure" || name == "ambiguous timeout"
			if (err == nil) != (name == "one action") || (actions == 1) != attempted || state.attempted != attempted || reads > 1 {
				t.Fatalf("fresh guard/action result: err=%v reads=%d actions=%d consumed=%v", err, reads, actions, state.attempted)
			}
			if attempted {
				if err := state.dispatch(ctx, target, []certutilFixtureDialog{d}, read, click); err == nil || actions != 1 || reads != 1 {
					t.Errorf("attempt retried: err=%v reads=%d actions=%d", err, reads, actions)
				}
			}
		})
	}
}
